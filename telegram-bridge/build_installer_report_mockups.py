def reconciliation_sheet(wb, manager):
    ws = wb.create_sheet("Отчёты для сверки", 1)
    widths = [7, 24, 54, 22, 12, 12, 14, 16, 12, 18, 15, 22] if manager else [7, 24, 54, 22, 12, 12, 14, 16, 12, 18]
    for col, width in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(col)].width = width
    ws.freeze_panes = "A4"
    current = 1
    for report, lines in source_reports.items():
        title_row = current
        ws.cell(current, 1, f"ОТЧЁТ ОТ {report} — построчная сверка с исходным PDF")
        ws.merge_cells(start_row=current, start_column=1, end_row=current, end_column=len(widths))
        ws.cell(current, 1).fill = PatternFill("solid", fgColor=NAVY)
        ws.cell(current, 1).font = Font(color=WHITE, bold=True, size=13)
        ws.cell(current, 1).alignment = Alignment(vertical="center")
        ws.row_dimensions[current].height = 26
        current += 1
        headers = ["№", "Объект/блок", "Строка исходного отчёта", "Тип", "Кол-во", "Ед.", "Ставка", "Сумма", "Знак", "Расчёт"]
        if manager:
            headers += ["Сделка", "Статус согласования"]
        for col, value in enumerate(headers, 1):
            c = ws.cell(current, col, value)
            c.fill = PatternFill("solid", fgColor="375A6C")
            c.font = Font(color=WHITE, bold=True)
            c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        current += 1
        detail_start = current
        previous_object = None
        object_start = current
        object_totals = []
        for number, (obj, source, kind, qty, unit, rate, amount, sign) in enumerate(lines, 1):
            if previous_object is not None and obj != previous_object:
                calc_row = current
                ws.cell(calc_row, 2, f"Расчётный итог блока «{previous_object}»")
                ws.cell(calc_row, 10, f"=SUM(J{object_start}:J{current-1})")
                ws.cell(calc_row, 2).font = ws.cell(calc_row, 10).font = Font(bold=True)
                ws.cell(calc_row, 2).fill = ws.cell(calc_row, 10).fill = PatternFill("solid", fgColor=BLUE)
                object_totals.append(calc_row)
                current += 1
                object_start = current
            values = [number, obj, source, kind, qty, unit, rate, amount, sign]
            impact = None if amount is None or sign == 0 else f"=H{current}*I{current}"
            values.append(impact)
            if manager:
                values += [None, "Требует проверки" if amount is None or "таблице" in source.casefold() else "Черновик"]
            for col, value in enumerate(values, 1):
                ws.cell(current, col, value)
            ws.row_dimensions[current].outlineLevel = 1
            if obj != previous_object:
                for col in range(1, len(widths) + 1):
                    ws.cell(current, col).fill = PatternFill("solid", fgColor="EAF2F6")
                ws.cell(current, 2).font = Font(bold=True)
            if kind in ("Итог из PDF", "Итог начислений из PDF", "Подытог из PDF"):
                for col in range(1, len(widths) + 1):
                    ws.cell(current, col).fill = PatternFill("solid", fgColor=YELLOW)
                    ws.cell(current, col).font = Font(bold=True)
            current += 1
            previous_object = obj
        calc_row = current
        ws.cell(calc_row, 2, f"Расчётный итог блока «{previous_object}»")
        ws.cell(calc_row, 10, f"=SUM(J{object_start}:J{current-1})")
        ws.cell(calc_row, 2).font = ws.cell(calc_row, 10).font = Font(bold=True)
        ws.cell(calc_row, 2).fill = ws.cell(calc_row, 10).fill = PatternFill("solid", fgColor=BLUE)
        object_totals.append(calc_row)
        current += 1
        ws.cell(current, 2, "РАСЧЁТНЫЙ ИТОГ ВСЕГО ОТЧЁТА")
        ws.cell(current, 10, "=" + "+".join(f"J{row}" for row in object_totals))
        for col in range(1, len(widths) + 1):
            ws.cell(current, col).fill = PatternFill("solid", fgColor="A9D18E")
            ws.cell(current, col).font = Font(bold=True)
        report_end = current
        ws.row_dimensions.group(detail_start, report_end - 1, hidden=False)
        current += 2
        ws.row_dimensions.group(title_row + 1, report_end, hidden=False)
    for row in ws.iter_rows():
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            if cell.column in (5, 7, 8, 9, 10):
                cell.number_format = '#,##0.00;[Red]-#,##0.00'
            cell.border = Border(bottom=thin)
    ws.sheet_properties.outlinePr.summaryBelow = True


